ALTER TABLE public.aquarium_status ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.feed_schedules ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.telemetry_logs ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Acesso publico aquarium_status" ON public.aquarium_status;
CREATE POLICY "Acesso publico aquarium_status" ON public.aquarium_status
  FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Acesso publico feed_schedules" ON public.feed_schedules;
CREATE POLICY "Acesso publico feed_schedules" ON public.feed_schedules
  FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Acesso publico telemetry_logs" ON public.telemetry_logs;
CREATE POLICY "Acesso publico telemetry_logs" ON public.telemetry_logs
  FOR ALL USING (true) WITH CHECK (true);

-- ============================================================================
-- HABILITAR REALTIME (PARA ATUALIZAÇÃO INSTANTÂNEA NO SITE E NO APK)
-- ============================================================================
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables
    WHERE pubname = 'supabase_realtime' AND tablename = 'aquarium_status'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.aquarium_status;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables
    WHERE pubname = 'supabase_realtime' AND tablename = 'feed_schedules'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.feed_schedules;
  End IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables
    WHERE pubname = 'supabase_realtime' AND tablename = 'telemetry_logs'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.telemetry_logs;
  END IF;
END $$;
