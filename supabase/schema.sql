-- 1. Tabela de Estado Atual de cada Aquário / ESP32 (vinculado por Usuário e Senha)
CREATE TABLE IF NOT EXISTS public.aquarium_status (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id TEXT,
  device_username TEXT UNIQUE,
  device_password TEXT,
  water_level_pct INT NOT NULL DEFAULT 0,
  distance_cm FLOAT NOT NULL DEFAULT 0,
  temperature_c FLOAT NOT NULL DEFAULT 26.0,
  pump_relay_on BOOLEAN NOT NULL DEFAULT true,
  pump_mode TEXT NOT NULL DEFAULT 'auto', -- 'auto' | 'manual'
  pump_cycle_minutes INT NOT NULL DEFAULT 45,
  feed_now_command BOOLEAN NOT NULL DEFAULT false,
  feed_now_portion TEXT NOT NULL DEFAULT 'Padrão (5g)',
  rtc_datetime TIMESTAMPTZ DEFAULT NOW(),
  rtc_set_command BOOLEAN NOT NULL DEFAULT false,
  wifi_setup_command BOOLEAN NOT NULL DEFAULT false,
  wifi_rssi INT DEFAULT -54,
  esp_last_seen TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Migração segura caso a tabela já tenha sido criada anteriormente
ALTER TABLE public.aquarium_status DROP CONSTRAINT IF EXISTS aquarium_status_id_check;
CREATE SEQUENCE IF NOT EXISTS public.aquarium_status_id_seq;
ALTER TABLE public.aquarium_status ALTER COLUMN id SET DEFAULT nextval('public.aquarium_status_id_seq');
SELECT setval('public.aquarium_status_id_seq', COALESCE((SELECT MAX(id) FROM public.aquarium_status), 1));

ALTER TABLE public.aquarium_status ADD COLUMN IF NOT EXISTS device_id TEXT;
ALTER TABLE public.aquarium_status ADD COLUMN IF NOT EXISTS device_username TEXT;
ALTER TABLE public.aquarium_status ADD COLUMN IF NOT EXISTS device_password TEXT;
ALTER TABLE public.aquarium_status ADD COLUMN IF NOT EXISTS temperature_c FLOAT NOT NULL DEFAULT 26.0;
ALTER TABLE public.aquarium_status ADD COLUMN IF NOT EXISTS rtc_datetime TIMESTAMPTZ DEFAULT NOW();
ALTER TABLE public.aquarium_status ADD COLUMN IF NOT EXISTS rtc_set_command BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE public.aquarium_status ADD COLUMN IF NOT EXISTS wifi_setup_command BOOLEAN NOT NULL DEFAULT false;

CREATE UNIQUE INDEX IF NOT EXISTS idx_aquarium_status_device_username
  ON public.aquarium_status (device_username);

-- 2. Tabela de Horários Programados do Alimentador Automático (por ESP32 / Usuário)
CREATE TABLE IF NOT EXISTS public.feed_schedules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_username TEXT DEFAULT 'admin',
  time TEXT NOT NULL,           -- Ex: '08:00', '14:00', '20:00'
  portion TEXT NOT NULL,        -- Ex: 'Leve (3g)', 'Padrão (5g)', 'Generosa (8g)'
  label TEXT DEFAULT 'Rotina',
  enabled BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.feed_schedules ADD COLUMN IF NOT EXISTS device_username TEXT DEFAULT 'admin';
CREATE INDEX IF NOT EXISTS idx_feed_schedules_device_username ON public.feed_schedules (device_username);

-- 3. Tabela de Histórico e Logs (vinculado por ESP32 / Usuário)
CREATE TABLE IF NOT EXISTS public.telemetry_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_username TEXT DEFAULT 'admin',
  event_type TEXT NOT NULL,     -- 'sensor' | 'pump' | 'feeder' | 'sync'
  water_level_pct INT,
  distance_cm FLOAT,
  temperature_c FLOAT,
  message TEXT NOT NULL,
  source TEXT NOT NULL DEFAULT 'ESP32 Wi-Fi',
  recorded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.telemetry_logs ADD COLUMN IF NOT EXISTS temperature_c FLOAT;
ALTER TABLE public.telemetry_logs ADD COLUMN IF NOT EXISTS device_username TEXT DEFAULT 'admin';
CREATE INDEX IF NOT EXISTS idx_telemetry_logs_recorded_at ON public.telemetry_logs (recorded_at DESC);
CREATE INDEX IF NOT EXISTS idx_telemetry_logs_device_username ON public.telemetry_logs (device_username);

-- ============================================================================
-- FUNÇÃO AUTOMÁTICA DE UPDATED_AT
-- ============================================================================
CREATE OR REPLACE FUNCTION public.update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_aquarium_status_updated_at ON public.aquarium_status;
CREATE TRIGGER trg_aquarium_status_updated_at
BEFORE UPDATE ON public.aquarium_status
FOR EACH ROW EXECUTE FUNCTION public.update_updated_at_column();

