-- 1. Tabela de Estado Atual do Aquário (1 linha única principal: id = 1)
CREATE TABLE IF NOT EXISTS public.aquarium_status (
  id INT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  water_level_pct INT NOT NULL DEFAULT 85,
  distance_cm FLOAT NOT NULL DEFAULT 8.1,
  pump_relay_on BOOLEAN NOT NULL DEFAULT true,
  pump_mode TEXT NOT NULL DEFAULT 'auto', -- 'auto' | 'manual'
  pump_cycle_minutes INT NOT NULL DEFAULT 45,
  feed_now_command BOOLEAN NOT NULL DEFAULT false,
  feed_now_portion TEXT NOT NULL DEFAULT 'Padrão (5g)',
  wifi_rssi INT DEFAULT -54,
  esp_last_seen TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Insere a linha inicial padrão caso não exista
INSERT INTO public.aquarium_status (id, water_level_pct, distance_cm, pump_relay_on, pump_mode)
VALUES (1, 85, 8.1, true, 'auto')
ON CONFLICT (id) DO NOTHING;

-- 2. Tabela de Horários Programados do Alimentador Automático
CREATE TABLE IF NOT EXISTS public.feed_schedules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  time TEXT NOT NULL,           -- Ex: '08:00', '14:00', '20:00'
  portion TEXT NOT NULL,        -- Ex: 'Leve (3g)', 'Padrão (5g)', 'Generosa (8g)'
  label TEXT DEFAULT 'Rotina',
  enabled BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Horários iniciais de exemplo (apenas se a tabela estiver vazia)
INSERT INTO public.feed_schedules (time, portion, label, enabled)
SELECT * FROM (VALUES
  ('08:00', 'Padrão (5g)', 'Manhã', true),
  ('14:00', 'Leve (3g)', 'Tarde', true),
  ('20:00', 'Padrão (5g)', 'Noite', true)
) AS seed(time, portion, label, enabled)
WHERE NOT EXISTS (SELECT 1 FROM public.feed_schedules);

-- 3. Tabela de Histórico e Logs (Suporta envios em tempo real e envios atrasados da fila offline do ESP32 ou Bluetooth do APK)
CREATE TABLE IF NOT EXISTS public.telemetry_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_type TEXT NOT NULL,     -- 'sensor' | 'pump' | 'feeder' | 'sync'
  water_level_pct INT,
  distance_cm FLOAT,
  message TEXT NOT NULL,
  source TEXT NOT NULL DEFAULT 'ESP32 Wi-Fi', -- 'ESP32 Wi-Fi' | 'Fila Offline ESP32' | 'Bluetooth APK' | 'Painel Web'
  recorded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), -- Horário real em que ocorreu no aquário
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()   -- Horário em que foi salvo na nuvem
);

CREATE INDEX IF NOT EXISTS idx_telemetry_logs_recorded_at ON public.telemetry_logs (recorded_at DESC);

-- ============================================================================
-- FUNÇÃO AUTOMÁTICA DE UPDATED_AT
-- ============================================================================
CREATE OR REPLACE FUNCTION public.update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_aquarium_status_updated_at ON public.aquarium_status;
CREATE TRIGGER trg_aquarium_status_updated_at
BEFORE UPDATE ON public.aquarium_status
FOR EACH ROW EXECUTE FUNCTION public.update_updated_at_column();

-- ============================================================================
-- POLÍTICAS DE ACESSO (RLS) — BASE ABERTA PARA PROTÓTIPO IOT (WEB + APK + ESP32)
-- Obs.: No futuro, você pode restringir por usuário autenticado (auth.uid()).
-- ============================================================================
ALTER TABLE public.aquarium_status ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.feed_schedules ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.telemetry_logs ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Acesso publico aquarium_status" ON public.aquarium_status;
CREATE POLICY "Acesso publico aquarium_status" ON public.aquarium_status
  FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Acesso publico feed_schedules" ON public.feed_schedules;
CREATE POLICY "Acesso publico feed_schedules" ON public.feed_schedules
  FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Acesso publico telemetry_logs" ON public.telemetry_logs;
CREATE POLICY "Acesso publico telemetry_logs" ON public.telemetry_logs
  FOR ALL USING (true) WITH CHECK (true);

-- ============================================================================
-- HABILITAR REALTIME (PARA ATUALIZAÇÃO INSTANTÂNEA NO SITE E NO APK)
-- ============================================================================
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables
    WHERE pubname = 'supabase_realtime' AND tablename = 'aquarium_status'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.aquarium_status;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables
    WHERE pubname = 'supabase_realtime' AND tablename = 'feed_schedules'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.feed_schedules;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables
    WHERE pubname = 'supabase_realtime' AND tablename = 'telemetry_logs'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.telemetry_logs;
  END IF;
END $$;
